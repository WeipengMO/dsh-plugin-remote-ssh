    // Notebook rendering for DSH's workspace document preview. Everything is
    // rendered as React text/elements; untrusted notebook HTML, SVG and scripts are NOT run.
    const NOTEBOOK_LIMIT = 12 * 1024 * 1024;
    function notebookText(value) {
      return Array.isArray(value) ? value.filter(part => typeof part === 'string').join('') :
        typeof value === 'string' ? value : '';
    }
    function parseNotebook(value) {
      if (!value || typeof value !== 'object' || value.nbformat !== 4 ||
          !Array.isArray(value.cells) || value.cells.length > 2000) {
        throw Error('请选择符合 nbformat 4 规范的 Jupyter Notebook（最多 2000 个单元格）');
      }
      return value;
    }
    function notebookInlineText(text) {
      const result = [];
      const pattern = /(\*\*[^*\n]+\*\*|`[^`\n]+`)/g;
      let last = 0;
      let found;
      while ((found = pattern.exec(text)) !== null) {
        if (found.index > last) result.push(text.slice(last, found.index));
        const raw = found[0];
        result.push(raw.startsWith('**')
          ? h('strong', { key: found.index }, raw.slice(2, -2))
          : h('code', { key: found.index }, raw.slice(1, -1)));
        last = found.index + raw.length;
      }
      if (last < text.length) result.push(text.slice(last));
      return result;
    }
    function notebookMarkdown(source) {
      const lines = source.split(/\r?\n/);
      const blocks = [];
      let fence = null;
      let pending = [];
      const flush = () => {
        if (pending.length) {
          blocks.push(h('p', { key: blocks.length }, notebookInlineText(pending.join(' '))));
          pending = [];
        }
      };
      for (const line of lines) {
        if (line.trim().startsWith(String.fromCharCode(96, 96, 96))) {
          if (fence === null) { flush(); fence = []; }
          else {
            blocks.push(h('pre', { key: blocks.length, className: 'rss-nb-md-code' }, fence.join('\n')));
            fence = null;
          }
          continue;
        }
        if (fence !== null) { fence.push(line); continue; }
        const head = line.match(/^(#{1,6})\s+(.+)/);
        if (head) {
          flush();
          blocks.push(h('div', { key: blocks.length, className: 'rss-nb-heading rss-nb-h' + head[1].length },
            notebookInlineText(head[2])));
        } else if (/^\s*[-*+]\s+/.test(line)) {
          flush();
          blocks.push(h('div', { key: blocks.length, className: 'rss-nb-listitem' }, '\u2022 ', notebookInlineText(line.replace(/^\s*[-*+]\s+/, ''))));
        } else if (/^\s*>\s?/.test(line)) {
          flush();
          blocks.push(h('blockquote', { key: blocks.length }, notebookInlineText(line.replace(/^\s*>\s?/, ''))));
        } else if (!line.trim()) flush();
        else pending.push(line.trim());
      }
      if (fence !== null) blocks.push(h('pre', { key: blocks.length }, fence.join('\n')));
      flush();
      return blocks;
    }

    // Notebook output may contain HTML generated by pandas. Rebuild only table
    // structure using safe React nodes; ignore attributes, scripts, CSS and SVG.
    function notebookHtmlTable(value, key) {
      const html = notebookText(value);
      if (!html || html.length > 500000 || !/<table\b/i.test(html) || typeof DOMParser === 'undefined') return null;
      // Whitelist markup BEFORE DOMParser: it must never see remote URLs,
      // embedded images, styles or other executable/resource-bearing nodes.
      const tokens = html.match(/<[^>]*>|[^<]+/g) || [];
      const safe = tokens.map(token => {
        const tag = /^<\s*(\/?)\s*(table|thead|tbody|tfoot|tr|td|th)\b[^>]*>$/i.exec(token);
        return tag ? '<' + (tag[1] ? '/' : '') + tag[2].toLowerCase() + '>'
          : token.startsWith('<') ? '' : token;
      }).join('');
      if (safe.length > 500000) return null;
      const parsed = new DOMParser().parseFromString(safe, 'text/html');
      const table = parsed.querySelector('table');
      if (!table) return null;
      const rows = Array.from(table.querySelectorAll('tr')).slice(0, 1500).map((tr, rowIndex) => {
        const cells = Array.from(tr.children).filter(el => /^(TH|TD)$/.test(el.tagName)).slice(0, 80);
        return h('tr', { key: rowIndex }, cells.map((cell, columnIndex) => h(
          cell.tagName === 'TH' ? 'th' : 'td',
          { key: columnIndex, scope: cell.tagName === 'TH' ? 'col' : undefined },
          (cell.textContent || '').trim().slice(0, 10000)
        )));
      });
      return rows.length ? h('div', { key, className: 'rss-nb-table-wrap', role: 'region',
        'aria-label': 'Notebook HTML 数据表格', tabIndex: 0 },
        h('table', { className: 'rss-nb-dataframe' }, h('tbody', null, rows))) : null;
    }

    // Some notebooks contain only a pandas text/plain representation.
    // Recognize its aligned index + column layout rather than displaying a
    // monospaced wall of text. Other stdout / prose remains unchanged.
    function notebookPlainTable(value, key) {
      const text = notebookText(value);
      if (!text || text.length > 250000) return null;
      const lines = text.trimEnd().split(/\r?\n/).filter(line => line.trim());
      if (lines.length < 2 || lines.length > 1501) return null;
      const names = lines[0].trim().split(/\s{2,}/);
      if (names.length < 2 || names.length > 80 || names.some(name => !name)) return null;
      const items = [];
      for (const line of lines.slice(1)) {
        if (/^\s*\[\d+ rows? x \d+ columns?\]\s*$/.test(line)) continue;
        if (!/^\s*\d+\s{2,}/.test(line)) return null;
        const fields = line.trim().split(/\s{2,}/);
        if (fields.length !== names.length + 1) return null;
        items.push(fields);
      }
      if (!items.length) return null;
      const rows = [['', ...names], ...items];
      return h('div', { key, className: 'rss-nb-table-wrap', role: 'region',
        'aria-label': 'Notebook 文本数据表格', tabIndex: 0 },
        h('table', { className: 'rss-nb-dataframe' },
          h('tbody', null, rows.map((fields, rowIndex) =>
            h('tr', { key: rowIndex }, fields.map((value, columnIndex) =>
              h(rowIndex === 0 || columnIndex === 0 ? 'th' : 'td',
                { key: columnIndex, scope: columnIndex === 0 ? 'row' : undefined }, value)))))));
    }

    function notebookHighlight(line, language) {
      if (language !== 'python') return line;
      const pieces = [];
      const tokens = /("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|#[^\n]*|\b\d+(?:\.\d+)?\b|\b[A-Za-z_]\w*\b)/g;
      const keywords = /^(?:and|as|assert|async|await|break|class|continue|def|del|elif|else|except|False|finally|for|from|global|if|import|in|is|lambda|None|nonlocal|not|or|pass|raise|return|True|try|while|with|yield|match|case)$/;
      const builtins = /^(?:print|len|str|int|float|dict|list|tuple|set|range|enumerate|zip|sum|min|max|open|isinstance|super)$/;
      let last = 0;
      let token;
      while ((token = tokens.exec(line)) !== null) {
        if (token.index > last) pieces.push(line.slice(last, token.index));
        const value = token[0];
        const kind = value[0] === '#' ? 'comment'
          : value[0] === '"' || value[0] === "'" ? 'string'
          : /^\d/.test(value) ? 'number'
          : keywords.test(value) ? 'keyword'
          : builtins.test(value) ? 'builtin'
          : /^\s*\(/.test(line.slice(tokens.lastIndex)) ? 'function'
          : '';
        pieces.push(kind ? h('span', { key: token.index, className: 'rss-nb-token-' + kind }, value) : value);
        last = tokens.lastIndex;
      }
      if (last < line.length) pieces.push(line.slice(last));
      return pieces.length ? pieces : ' ';
    }

    function notebookCode(source, language) {
      const lines = source.slice(0, 1000000).split(/\r?\n/);
      const visible = lines.slice(0, 5000);
      return h('div', { className: 'rss-nb-code-scroll', role: 'region',
        'aria-label': '只读代码，带行号', tabIndex: 0 },
        h('div', { className: 'rss-nb-code-lines' },
          visible.map((line, index) => h('div', { key: index, className: 'rss-nb-code-line' },
            h('span', { className: 'rss-nb-line-number', 'aria-hidden': true }, String(index + 1)),
            h('span', { className: 'rss-nb-line-content' }, notebookHighlight(line, language))))),
        lines.length > visible.length &&
          h('div', { className: 'rss-nb-truncated' }, '代码过长，仅显示前 5000 行'));
    }

    function notebookOutputs(outputs) {
      return (Array.isArray(outputs) ? outputs : []).map((output, index) => {
        if (!output || typeof output !== 'object') return null;
        if (output.output_type === 'stream') {
          return h('pre', { key: index, className: 'rss-nb-stream' },
            notebookText(output.text).slice(0, 500000));
        }
        if (output.output_type === 'error') {
          return h('pre', { key: index, className: 'rss-nb-error' },
            notebookText(output.traceback).slice(0, 500000) ||
            [output.ename, output.evalue].filter(Boolean).join(': '));
        }
        const data = output.data || {};
        for (const mime of ['image/png', 'image/jpeg', 'image/gif']) {
          const encoded = notebookText(data[mime]).replace(/\s+/g, '');
          if (encoded && encoded.length <= NOTEBOOK_LIMIT * 2 && /^[A-Za-z0-9+/]*={0,2}$/.test(encoded)) {
            return h('div', { key: index, className: 'rss-nb-output' },
              h('img', { src: 'data:' + mime + ';base64,' + encoded, alt: 'Notebook image output', loading: 'lazy' }));
          }
        }
        const table = notebookHtmlTable(data['text/html'], index);
        if (table) return table;
        const richMarkdown = notebookText(data['text/markdown']);
        if (richMarkdown) return h('div', { key: index, className: 'rss-nb-markdown rss-nb-rich-markdown' },
          notebookMarkdown(richMarkdown.slice(0, 500000)));
        const plain = notebookText(data['text/plain']);
        if (plain) return notebookPlainTable(plain, index) ||
          h('pre', { key: index, className: 'rss-nb-output' }, plain.slice(0, 500000));
        return h('div', { key: index, className: 'rss-nb-muted' },
          '此输出仅提供不受支持的 HTML/SVG/交互内容，因此未执行或嵌入。');
      });
    }

    function NotebookDocument({ notebook, filename }) {
      const language = String(notebook.metadata?.language_info?.name ||
        notebook.metadata?.kernelspec?.language || 'python').toLowerCase();
      return h('div', { className: 'rss-nb-document' },
        h('header', { className: 'rss-nb-document-head' },
          h('span', { className: 'rss-nb-document-title', title: filename }, filename),
          h('span', { className: 'rss-nb-document-meta' }, notebook.cells.length, ' 个单元格 · 只读')),
        h('main', { className: 'rss-nb-page' },
          notebook.cells.map((cell, index) => h('section', {
              key: cell.id || index,
              className: 'rss-nb-cell rss-nb-' + cell.cell_type
            },
            cell.cell_type === 'markdown'
              ? h('div', { className: 'rss-nb-markdown' }, notebookMarkdown(notebookText(cell.source)))
              : h('div', { className: 'rss-nb-cell-grid' },
                  h('div', { className: 'rss-nb-cell-label' },
                    cell.cell_type === 'code' ? 'In [' + (cell.execution_count ?? ' ') + ']:' : 'Raw'),
                  h('div', { className: 'rss-nb-cell-main' },
                    notebookCode(notebookText(cell.source), language),
                    cell.cell_type === 'code' && notebookOutputs(cell.outputs)))))));
    }
    function notebookFilename(resourceAddress) {
      const value = typeof resourceAddress === 'string' ? resourceAddress : '';
      const cleaned = value.split(/[?#]/)[0];
      const parts = cleaned.split(/[\\/]/).filter(Boolean);
      return parts.length ? parts[parts.length - 1] : 'Notebook';
    }
    // Body for DSH's right-sidebar document preview. When a notebook is opened
    // from the workspace file tree, DSH reads the file (local or remote-SSH
    // routed) as complete bytes and hands them to this renderer; we decode,
    // validate nbformat 4, and render it read-only. Nothing is executed.
    function NotebookFileBody(props) {
      const content = props && props.content;
      const data = content && content.kind === 'bytes' ? content.data : undefined;
      if (data === undefined) {
        return h('div', { className: 'rss-nb-muted', role: 'status' }, '正在读取 Notebook…');
      }
      if (data.byteLength > NOTEBOOK_LIMIT) {
        return h('div', { className: 'rss-nb-alert', role: 'alert' }, 'Notebook 超过 12 MiB 预览限制。');
      }
      let notebook;
      try {
        const text = new TextDecoder('utf-8').decode(data);
        notebook = parseNotebook(JSON.parse(text));
      } catch (e) {
        return h('div', { className: 'rss-nb-alert', role: 'alert' },
          '无法预览 Notebook：' + (e && e.message ? e.message : String(e)));
      }
      return h(NotebookDocument, { notebook, filename: notebookFilename(props && props.resourceAddress) });
    }
    const NOTEBOOK_BODY_ID = 'dsh-plugin-remote-ssh/notebook';
    function registerNotebookPreview(ctx) {
      // Register .ipynb as an *extension* renderer in DSH's workspace document
      // preview. Extension priority wins over the built-in plain-text fallback,
      // so opening a Notebook from the workspace renders it instead of raw JSON.
      ctx.effect(() => ctx.documentPreviews.register({
        id: NOTEBOOK_BODY_ID,
        extensions: ['ipynb'],
        priority: 'extension',
        title: () => 'Notebook',
        loading: 'bytes-complete',
      }));
      ctx.effect(() => ctx.slots.inject('sidebar.right.tab.document', () =>
        ctx.slots.register({
          name: 'sidebar.right.tab.document',
          key: NOTEBOOK_BODY_ID,
        }, NotebookFileBody)));
    }

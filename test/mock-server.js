import path from 'node:path';
import ssh2 from '../vendor/ssh2/lib/index.js';

const { Server, utils } = ssh2;

const STATUS = { OK: 0, EOF: 1, NO_SUCH_FILE: 2, PERMISSION_DENIED: 3, FAILURE: 4 };
const OPEN = { READ: 0x1, WRITE: 0x2, APPEND: 0x4, CREAT: 0x8, TRUNC: 0x10, EXCL: 0x20 };
const S_IFDIR = 0o040000;
const S_IFREG = 0o100000;

function attrs(node) {
  return {
    mode: (node.kind === 'dir' ? S_IFDIR : S_IFREG) | node.mode,
    size: node.kind === 'dir' ? 4096 : node.data.length,
    uid: 1000,
    gid: 1000,
    atime: Math.floor(node.atime / 1000),
    mtime: Math.floor(node.mtime / 1000),
  };
}

class MemoryFs {
  constructor() {
    this.root = { kind: 'dir', mode: 0o755, mtime: Date.now(), atime: Date.now(), children: new Map() };
    this.seq = 1;
  }

  normalize(input) {
    const value = path.posix.normalize(input.startsWith('/') ? input : `/${input}`);
    if (value === '/..' || value.startsWith('/../')) throw new Error('escape');
    return value === '/' ? '/' : value.replace(/\/+$/, '');
  }

  lookup(input) {
    const normalized = this.normalize(input);
    if (normalized === '/') return { node: this.root, parent: undefined, name: '' };
    const parts = normalized.slice(1).split('/');
    let node = this.root;
    for (let index = 0; index < parts.length - 1; index += 1) {
      const child = node.children?.get(parts[index]);
      if (child === undefined || child.kind !== 'dir') return undefined;
      node = child;
    }
    const name = parts[parts.length - 1];
    return { node: node.children?.get(name), parent: node, name };
  }

  ensureDir(input) {
    const normalized = this.normalize(input);
    if (normalized === '/') return this.root;
    const parts = normalized.slice(1).split('/');
    let node = this.root;
    for (const part of parts) {
      let child = node.children.get(part);
      if (child === undefined) {
        child = { kind: 'dir', mode: 0o755, mtime: Date.now(), atime: Date.now(), children: new Map() };
        node.children.set(part, child);
      }
      if (child.kind !== 'dir') throw new Error('not a directory');
      node = child;
    }
    return node;
  }

  setFile(input, data) {
    const normalized = this.normalize(input);
    const parentPath = path.posix.dirname(normalized);
    const parent = this.ensureDir(parentPath);
    const name = path.posix.basename(normalized);
    let node = parent.children.get(name);
    if (node === undefined || node.kind !== 'file') {
      node = { kind: 'file', mode: 0o644, mtime: Date.now(), atime: Date.now(), data: Buffer.alloc(0) };
      parent.children.set(name, node);
    }
    node.data = Buffer.from(data);
    node.mtime = Date.now();
  }

  list(input) {
    const found = this.lookup(input);
    if (found?.node === undefined || found.node.kind !== 'dir') return undefined;
    return [...found.node.children.entries()].map(([name, node]) => ({ name, node }));
  }
}

function parseHandle(handle) {
  return Number(handle.toString());
}

/**
 * Deliberately small in-memory SSH/SFTP server used by the automated tests.
 * It verifies a real SSH handshake and exercises the same SFTP wire protocol as
 * OpenSSH, but it is not a production server and does not implement all SFTP
 * extensions.
 */
export class MockSshServer {
  /**
   * @param {{ clientPrivateKey?: string }} [options] Supply a private key that
   * already exists on disk (e.g. one generated by Windows OpenSSH with a secure
   * ACL), so the same identity can be used by both ssh2 and system ssh.exe.
   */
  constructor(options = {}) {
    this.fs = new MemoryFs();
    this.hostKey = utils.generateKeyPairSync('ed25519');
    this.clientKey = {
      private: options.clientPrivateKey ?? utils.generateKeyPairSync('ed25519').private,
    };
    this.clientPublic = utils.parseKey(this.clientKey.private).getPublicSSH();
    this.handles = new Map();
    this.sockets = new Set();
    this.seq = 1;
    this.server = new Server({ hostKeys: [this.hostKey.private] }, (client) => {
      this.sockets.add(client);
      client.on('close', () => this.sockets.delete(client));
      client.on('error', () => {});
      client.on('authentication', (ctx) => {
        if (ctx.method === 'publickey' && Buffer.compare(ctx.key.data, this.clientPublic) === 0) ctx.accept();
        else ctx.reject();
      });
      client.on('ready', () => {
        client.on('session', (accept) => {
          const session = accept();
          session.on('sftp', (acceptSftp) => this.attachSftp(acceptSftp()));
          session.on('exec', (acceptExec, _reject, info) => this.attachExec(acceptExec(), info.command));
        });
      });
    });
  }

  async start() {
    await new Promise((resolve, reject) => {
      this.server.once('error', reject);
      this.server.listen(0, '127.0.0.1', () => resolve());
    });
    const address = this.server.address();
    this.port = address.port;
    return this;
  }

  async stop() {
    for (const socket of this.sockets) {
      try {
        socket.end();
      } catch {
        // ignore
      }
    }
    await new Promise((resolve) => this.server.close(resolve));
  }

  handle(node, extra = {}) {
    const id = this.seq++;
    this.handles.set(id, { node, ...extra });
    return Buffer.from(String(id));
  }

  attachSftp(sftp) {
    const fs = this.fs;
    sftp.on('OPEN', (reqid, filename, flags, attributes) => {
      const found = fs.lookup(filename);
      const exists = found?.node !== undefined;
      if ((flags & OPEN.EXCL) !== 0 && exists) return sftp.status(reqid, STATUS.FAILURE);
      if (!exists && (flags & OPEN.CREAT) === 0) return sftp.status(reqid, STATUS.NO_SUCH_FILE);
      if (exists && found.node.kind !== 'file') return sftp.status(reqid, STATUS.FAILURE);
      let node = found?.node;
      if (node === undefined) {
        fs.setFile(filename, Buffer.alloc(0));
        node = fs.lookup(filename).node;
      }
      if ((flags & OPEN.TRUNC) !== 0 && (flags & OPEN.WRITE) !== 0) node.data = Buffer.alloc(0);
      if (attributes?.mode !== undefined) node.mode = attributes.mode & 0o777;
      const handle = this.handle(node, { position: (flags & OPEN.APPEND) !== 0 ? node.data.length : 0 });
      sftp.handle(reqid, handle);
    });
    sftp.on('READ', (reqid, handle, offset, length) => {
      const entry = this.handles.get(parseHandle(handle));
      if (entry === undefined || entry.node.kind !== 'file') return sftp.status(reqid, STATUS.FAILURE);
      const start = offset ?? entry.position;
      if (start >= entry.node.data.length) return sftp.status(reqid, STATUS.EOF);
      const data = entry.node.data.subarray(start, start + length);
      entry.position = start + data.length;
      sftp.data(reqid, data);
    });
    sftp.on('WRITE', (reqid, handle, offset, data) => {
      const entry = this.handles.get(parseHandle(handle));
      if (entry === undefined || entry.node.kind !== 'file') return sftp.status(reqid, STATUS.FAILURE);
      const start = offset ?? entry.position;
      const needed = start + data.length;
      if (needed > entry.node.data.length) {
        const grown = Buffer.alloc(needed);
        entry.node.data.copy(grown);
        entry.node.data = grown;
      }
      data.copy(entry.node.data, start);
      entry.node.mtime = Date.now();
      entry.position = needed;
      sftp.status(reqid, STATUS.OK);
    });
    sftp.on('CLOSE', (reqid, handle) => {
      this.handles.delete(parseHandle(handle));
      sftp.status(reqid, STATUS.OK);
    });
    sftp.on('STAT', (reqid, filename) => this.respondStat(sftp, reqid, filename));
    sftp.on('LSTAT', (reqid, filename) => this.respondStat(sftp, reqid, filename));
    sftp.on('FSTAT', (reqid, handle) => {
      const entry = this.handles.get(parseHandle(handle));
      if (entry === undefined) return sftp.status(reqid, STATUS.FAILURE);
      sftp.attrs(reqid, attrs(entry.node));
    });
    sftp.on('OPENDIR', (reqid, filename) => {
      const found = fs.lookup(filename);
      if (found?.node === undefined) return sftp.status(reqid, STATUS.NO_SUCH_FILE);
      if (found.node.kind !== 'dir') return sftp.status(reqid, STATUS.FAILURE);
      sftp.handle(reqid, this.handle(found.node, { dirEntries: fs.list(filename), cursor: 0 }));
    });
    sftp.on('READDIR', (reqid, handle) => {
      const entry = this.handles.get(parseHandle(handle));
      if (entry === undefined || entry.dirEntries === undefined) return sftp.status(reqid, STATUS.FAILURE);
      const remaining = entry.dirEntries.slice(entry.cursor);
      if (remaining.length === 0) return sftp.status(reqid, STATUS.EOF);
      entry.cursor = entry.dirEntries.length;
      sftp.name(
        reqid,
        remaining.map(({ name, node }) => ({
          filename: name,
          longname: `${node.kind === 'dir' ? 'd' : '-'}rw-r--r-- 1 test test ${node.kind === 'dir' ? 4096 : node.data.length} Jan 1 00:00 ${name}`,
          attrs: attrs(node),
        })),
      );
    });
    sftp.on('REALPATH', (reqid, filename) => {
      const normalized = fs.normalize(filename);
      const found = fs.lookup(normalized);
      if (found?.node === undefined) return sftp.status(reqid, STATUS.NO_SUCH_FILE);
      sftp.name(reqid, [{ filename: normalized, longname: normalized, attrs: attrs(found.node) }]);
    });
    sftp.on('RENAME', (reqid, oldPath, newPath) => {
      const source = fs.lookup(oldPath);
      if (source?.node === undefined) return sftp.status(reqid, STATUS.NO_SUCH_FILE);
      const destination = fs.lookup(newPath);
      if (destination?.node !== undefined) {
        const data = source.node.kind === 'file' ? source.node.data : undefined;
        if (data === undefined || destination.node.kind !== 'file') return sftp.status(reqid, STATUS.FAILURE);
        source.parent.children.delete(source.name);
        fs.setFile(newPath, data);
      } else {
        source.parent.children.delete(source.name);
        const targetParent = fs.ensureDir(path.posix.dirname(fs.normalize(newPath)));
        targetParent.children.set(path.posix.basename(fs.normalize(newPath)), source.node);
      }
      sftp.status(reqid, STATUS.OK);
    });
    sftp.on('REMOVE', (reqid, filename) => {
      const found = fs.lookup(filename);
      if (found?.node === undefined) return sftp.status(reqid, STATUS.NO_SUCH_FILE);
      if (found.node.kind !== 'file') return sftp.status(reqid, STATUS.FAILURE);
      found.parent.children.delete(found.name);
      sftp.status(reqid, STATUS.OK);
    });
    sftp.on('MKDIR', (reqid, filename) => {
      try {
        fs.ensureDir(filename);
        sftp.status(reqid, STATUS.OK);
      } catch {
        sftp.status(reqid, STATUS.FAILURE);
      }
    });
    sftp.on('RMDIR', (reqid, filename) => {
      const found = fs.lookup(filename);
      if (found?.node === undefined) return sftp.status(reqid, STATUS.NO_SUCH_FILE);
      if (found.node.kind !== 'dir' || found.node.children.size > 0) return sftp.status(reqid, STATUS.FAILURE);
      found.parent.children.delete(found.name);
      sftp.status(reqid, STATUS.OK);
    });
    sftp.on('SETSTAT', (reqid, filename, attributes) => {
      const found = fs.lookup(filename);
      if (found?.node === undefined) return sftp.status(reqid, STATUS.NO_SUCH_FILE);
      if (attributes.mode !== undefined) found.node.mode = attributes.mode & 0o777;
      if (attributes.mtime !== undefined) found.node.mtime = attributes.mtime * 1000;
      sftp.status(reqid, STATUS.OK);
    });
    sftp.on('FSETSTAT', (reqid, handle, attributes) => {
      const entry = this.handles.get(parseHandle(handle));
      if (entry === undefined) return sftp.status(reqid, STATUS.FAILURE);
      if (attributes.mode !== undefined) entry.node.mode = attributes.mode & 0o777;
      sftp.status(reqid, STATUS.OK);
    });
    sftp.on('error', () => {});
    sftp.on('EXTENDED', (reqid) => sftp.status(reqid, STATUS.FAILURE));
  }

  respondStat(sftp, reqid, filename) {
    const found = this.fs.lookup(filename);
    if (found?.node === undefined) return sftp.status(reqid, STATUS.NO_SUCH_FILE);
    sftp.attrs(reqid, attrs(found.node));
  }

  attachExec(stream, command) {
    const cwdMatch = command.match(/^cd -- '((?:[^']|'\\'')*)'/s);
    const cwd = cwdMatch === null ? '/' : cwdMatch[1].replaceAll("'\\''", "'");
    const scriptMatch = command.match(/bash -lc '((?:[^']|'\\'')*)'/s);
    const script = scriptMatch === null ? command : scriptMatch[1].replaceAll("'\\''", "'");
    let stdout = '';
    let stderr = '';
    let code = 0;
    if (script.includes('printf') && script.includes('remote-ssh-ok')) {
      stdout = `remote-ssh-ok\n${cwd}\nLinux\n`;
    } else if (script === 'pwd') {
      stdout = `${cwd}\n`;
    } else if (script.startsWith('echo ')) {
      stdout = `${script.slice(5)}\n`;
    } else if (script.includes('false')) {
      code = 1;
    } else {
      stderr = `mock server does not implement: ${script}\n`;
      code = 127;
    }
    if (stdout.length > 0) stream.write(stdout);
    if (stderr.length > 0 && stream.stderr) stream.stderr.write(stderr);
    stream.exit(code);
    stream.end();
  }
}

const isMain = process.argv[1] !== undefined && import.meta.url === new URL(`file://${process.argv[1].replaceAll('\\', '/')}`).href;
if (isMain) {
  const server = await new MockSshServer().start();
  process.stdout.write(`${server.port}\n`);
  process.on('SIGTERM', async () => {
    await server.stop();
    process.exit(0);
  });
}
